"""Check release labels against the canonical source version, without importing the GUI."""

import argparse
import ast
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def source_version(root=ROOT):
    tree = ast.parse((root / "src/tresor/__init__.py").read_text(encoding="utf-8"))
    values = [
        ast.literal_eval(node.value)
        for node in tree.body
        if isinstance(node, ast.Assign)
        and any(
            isinstance(target, ast.Name) and target.id == "__version__" for target in node.targets
        )
    ]
    if len(values) != 1 or not isinstance(values[0], str):
        raise ValueError("Exactly one literal source version is required")
    if not re.fullmatch(r"(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)", values[0]):
        raise ValueError("Release version must use major.minor.patch")
    if any(int(part) > 65535 for part in values[0].split(".")):
        raise ValueError("Windows version component exceeds 65535")
    return values[0]


def windows_resource(version):
    parts = ", ".join([*version.split("."), "0"])
    return f"""# Generated by scripts/check_release.py --write; source: src/tresor/__init__.py
VSVersionInfo(
  ffi=FixedFileInfo(filevers=({parts}), prodvers=({parts}), mask=0x3f,
    flags=0x0, OS=0x40004, fileType=0x1, subtype=0x0, date=(0, 0)),
  kids=[StringFileInfo([StringTable('040904B0', [
    StringStruct('FileDescription', 'Tresor - local credential vault'),
    StringStruct('FileVersion', '{version}'),
    StringStruct('ProductName', 'Tresor'),
    StringStruct('ProductVersion', '{version}'),
    StringStruct('OriginalFilename', 'Tresor.exe')
  ])]), VarFileInfo([VarStruct('Translation', [1033, 1200])])]
)
"""


def check(root=ROOT, tag=None, write=False):
    version = source_version(root)
    project = (root / "pyproject.toml").read_text(encoding="utf-8")
    if (
        'dynamic = ["version"]' not in project
        or 'version = {attr = "tresor.__version__"}' not in project
    ):
        raise ValueError("Packaging must read the canonical source version")
    if tag is not None and tag != "v" + version:
        raise ValueError(f"Tag must equal v{version}")
    badge_pattern = (
        r"\[!\[Version [^\]]+\]\(https://img\.shields\.io/badge/Version-[^)]+\)\]\(CHANGELOG\.md\)"
    )
    expected = f"[![Version {version}](https://img.shields.io/badge/Version-{version}-blue.svg)](CHANGELOG.md)"
    for name in ("README.md", "README.en.md"):
        target = root / name
        text = target.read_text(encoding="utf-8")
        badges = re.findall(badge_pattern, text)
        if len(badges) != 1:
            raise ValueError(f"Exactly one version badge required in {name}")
        if write:
            target.write_text(re.sub(badge_pattern, expected, text), encoding="utf-8", newline="\n")
        elif badges[0] != expected:
            raise ValueError(f"Version label drift in {name}")
    resource = root / "packaging/version_info.txt"
    expected_resource = windows_resource(version)
    if write:
        resource.write_text(expected_resource, encoding="utf-8", newline="\n")
    elif not resource.is_file() or resource.read_text(encoding="utf-8") != expected_resource:
        raise ValueError("Windows resource version drift")
    return version


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--tag")
    args = parser.parse_args()
    print(check(tag=args.tag, write=args.write))
